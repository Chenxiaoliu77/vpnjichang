#!/usr/bin/env node
/**
 * render-readme.mjs — 由 data/links.json 重新生成 README.md 中的收录清单表格与条目正文。
 *
 * data/links.json 是唯一真源；README 中由本脚本托管的区块被标记注释包住，
 * 手工改这些区块会在下次渲染时被覆盖（CI 用 --check 校验两者一致）。
 *
 * 用法：node scripts/render-readme.mjs          # 写入 README.md
 *       node scripts/render-readme.mjs --check  # 只校验是否一致（不一致则退出码 1）
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'data', 'links.json');
const README = join(ROOT, 'README.md');
const CHECK = process.argv.includes('--check');

const BT = String.fromCharCode(96);

const doc = JSON.parse(readFileSync(DATA, 'utf8'));

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

const KIND_LABEL = {
  'hash-deep-link': '客户端深链（hash）',
  'path-referral': '服务端推广链接（query）',
  'path-page': '站内页面',
  plain: '普通链接'
};

function renderTable() {
  const head = [
    '| # | 名称 | 类型 | 链接形式 | 推广码 | 渠道标记 | 备用入口 |',
    '| --- | --- | --- | --- | --- | --- | --- |'
  ];
  const rows = doc.links.map((l, i) => {
    const backup = l.backupUrls.length ? l.backupUrls.map((u) => '[备用](' + u + ')').join(' ') : '—';
    const cells = [
      String(i + 1),
      esc(l.name),
      esc(l.categoryLabel),
      esc(KIND_LABEL[l.urlKind] || l.urlKind),
      l.referralCode ? BT + l.referralCode + BT : '—',
      l.cover ? BT + l.cover + BT : '—',
      backup
    ];
    return '| ' + cells.join(' | ') + ' |';
  });
  return head.concat(rows).join('\n');
}

function renderDetails() {
  return doc.links.map((l, i) => {
    const out = [];
    out.push('### ' + (i + 1) + '. ' + l.name + ' — ' + l.nameZh);
    out.push('');
    out.push('- **收录地址**：<' + l.url + '>');
    out.push('- **类型**：' + l.categoryLabel + '（链接形式：' + (KIND_LABEL[l.urlKind] || l.urlKind) + '）');
    if (l.referralCode) out.push('- **推广码**：' + BT + l.referralCode + BT);
    if (l.cover) out.push('- **渠道标记**：' + BT + l.cover + BT);
    if (l.punycodeDomain) out.push('- **域名**：Punycode ' + BT + l.punycodeDomain + BT + ' → Unicode ' + BT + l.unicodeDomain + BT);
    else if (l.unicodeDomain) out.push('- **域名**：' + BT + l.unicodeDomain + BT);
    out.push('- **用途**：' + l.purpose);
    out.push('- **标签**：' + BT + l.tags.join(BT + ' ' + BT) + BT);
    if (l.pricing.length) {
      out.push('- **公示套餐**：');
      for (const p of l.pricing) out.push('  - ' + p.plan + ' — ' + p.price);
    }
    if (l.platforms.length) out.push('- **支持平台**：' + l.platforms.join('、'));
    if (l.protocols.length) out.push('- **客户端/协议标识**：' + BT + l.protocols.join(BT + ' ' + BT) + BT);
    if (l.backupUrls.length) out.push('- **备用入口**：' + l.backupUrls.map((u) => '<' + u + '>').join('、'));
    if (l.contact.length) out.push('- **客服/社群**：' + l.contact.map((u) => '<' + u + '>').join('、'));
    out.push('');
    out.push('**说明**');
    out.push('');
    for (const d of l.description) out.push('- ' + d);
    out.push('');
    const v = l.verified;
    out.push('> 核验记录（' + v.checkedAt + '，' + v.method + '）：HTTP ' + v.httpStatus +
      (v.finalUrl ? ' → ' + v.finalUrl : '') + '。' + v.note);
    out.push('');
    return out.join('\n');
  }).join('\n---\n\n');
}

function replaceBlock(text, name, body) {
  const begin = '<!-- BEGIN:' + name + ' (generated by scripts/render-readme.mjs; do not edit by hand) -->';
  const end = '<!-- END:' + name + ' -->';
  const i = text.indexOf(begin);
  const j = text.indexOf(end);
  if (i === -1 || j === -1) {
    console.error('README.md 缺少 ' + name + ' 区块标记');
    process.exit(2);
  }
  return text.slice(0, i + begin.length) + '\n' + body + '\n' + text.slice(j);
}

let readme = readFileSync(README, 'utf8');

// 最后更新徽章：由 data/links.json 的 updatedAt 渲染，避免手写日期与数据脱节
const badgeRe = /^\[!\[Last update\]\([^)]*\)\]\([^)]*\)\s*$/m;
const badge = '[![' + 'Last update](https://img.shields.io/badge/last%20update-' +
  doc.updatedAt.replace(/-/g, '--') + '-informational)](data/links.json)';
if (!badgeRe.test(readme)) {
  console.error('README.md 缺少 Last update 徽章');
  process.exit(2);
}
readme = readme.replace(badgeRe, badge);
readme = replaceBlock(readme, 'LINKS_TABLE', renderTable());
readme = replaceBlock(readme, 'LINKS_DETAILS', renderDetails());

if (CHECK) {
  if (readFileSync(README, 'utf8') !== readme) {
    console.error('README.md 与 data/links.json 渲染结果不一致，请运行：node scripts/render-readme.mjs');
    process.exit(1);
  }
  console.log('README.md 与 data/links.json 一致。');
} else {
  writeFileSync(README, readme, 'utf8');
  console.log('已根据 data/links.json 渲染 README.md（' + doc.links.length + ' 条）。');
}
